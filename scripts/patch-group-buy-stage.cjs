const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..'), stage = path.join(root, '.deploy-group-buy');
const source = fs.readFileSync(path.join(root, 'functions/core.js'), 'utf8').replace(/\r\n/g, '\n');
let core = fs.readFileSync(path.join(stage, 'functions/core.js'), 'utf8').replace(/\r\n/g, '\n');
core = core.replace('createHandler({ store, verifyToken,', 'createHandler({ store, groupBuy, verifyToken,');
const loopStart = '        for (const event of body.events) {';
const loopEnd = '        await store.markVerified';
const from = core.indexOf(loopStart), to = core.indexOf(loopEnd, from);
if (from < 0 || to < 0) throw Error('Webhook patch anchors missing');
core = core.slice(0, from) + source.slice(source.indexOf(loopStart), source.indexOf(loopEnd, source.indexOf(loopStart))) + core.slice(to);
const api = source.slice(source.indexOf("      if (path === '/api/line/group-buy/activation'"), source.indexOf('      if (path === "/api/line/ai-settings"'));
if (!core.includes("'/api/line/group-buy/activation'")) core = core.replace('      if (path === "/api/line/ai-settings"', () => api + '      if (path === "/api/line/ai-settings"');
fs.writeFileSync(path.join(stage, 'functions/core.js'), core);
let index = fs.readFileSync(path.join(stage, 'functions/index.js'), 'utf8');
if (!index.includes('import { createGroupBuy }')) index = index.replace('import { createStore } from "./store.js";', 'import { createStore } from "./store.js";\nimport { createGroupBuy } from "./group-buy.js";');
index = index.replace('createHandler({ store: createStore(getFirestore()), verifyToken:', 'createHandler({ store: createStore(getFirestore()), groupBuy: createGroupBuy(getFirestore(), { getOpenAiKey: () => openAiKey.value() }), verifyToken:');
fs.writeFileSync(path.join(stage, 'functions/index.js'), index);
fs.copyFileSync(path.join(root, 'functions/group-buy.js'), path.join(stage, 'functions/group-buy.js'));
const config = JSON.parse(fs.readFileSync(path.join(stage, 'firebase.json'), 'utf8'));
config.hosting.rewrites = config.hosting.rewrites.map(({ glob, ...item }) => ({ ...item, source: item.source || glob }));
fs.writeFileSync(path.join(stage, 'firebase.json'), JSON.stringify(config, null, 2));
console.log('Patched only group-buy code into production snapshot.');
